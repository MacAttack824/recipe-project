create table public.tags (
  tag_id bigint generated by default as identity not null,
  tag_name text not null,
  constraint tags_pkey primary key (tag_id)
) TABLESPACE pg_default;

create table public.ingredients (
  ingredient_id bigint generated by default as identity not null,
  ingredient_name text not null,
  ingredient_type text not null,
  constraint ingredients_pkey primary key (ingredient_id)
) TABLESPACE pg_default;

create table public.recipes (
  recipe_id bigint generated by default as identity not null,
  recipe_name text not null,
  cook_time integer not null,
  cuisine_style text not null,
  servings smallint not null,
  source_recipe_number text null,
  subtitle text null,
  recipe_type text not null,
  constraint recipes_pkey primary key (recipe_id),
  constraint recipes_recipe_name_key unique (recipe_name)
) TABLESPACE pg_default;

create table public.recipe_ingredients (
  recipe_ingredient_id bigint generated by default as identity not null,
  ingredient_id bigint not null,
  recipe_id bigint not null,
  quantity numeric not null,
  measurement_unit text not null,
  preparation_note text null,
  constraint recipe_ingredients_pkey primary key (recipe_ingredient_id),
  constraint recipe_ingredients_ingredient_id_fkey foreign KEY (ingredient_id) references ingredients (ingredient_id),
  constraint recipe_ingredients_recipe_id_fkey foreign KEY (recipe_id) references recipes (recipe_id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create table public.steps (
  step_id bigint generated by default as identity not null,
  recipe_id bigint not null,
  step_title text not null,
  instructions text not null,
  step_number smallint not null,
  constraint steps_pkey primary key (step_id),
  constraint steps_recipe_id_fkey foreign KEY (recipe_id) references recipes (recipe_id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create table public.recipe_sides (
  main_recipe_id bigint not null,
  side_recipe_id bigint not null,
  constraint recipe_sides_pkey primary key (main_recipe_id, side_recipe_id),
  constraint recipe_sides_main_recipe_id_fkey foreign KEY (main_recipe_id) references recipes (recipe_id) on update CASCADE on delete CASCADE,
  constraint recipe_sides_side_recipe_id_fkey foreign KEY (side_recipe_id) references recipes (recipe_id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create table public.recipe_tags (
  recipe_tag_id bigint generated by default as identity not null,
  recipe_id bigint not null,
  tag_id bigint not null,
  constraint recipe_tag_pkey primary key (recipe_tag_id),
  constraint recipe_tag_recipe_id_tag_id_key unique (recipe_id, tag_id),
  constraint recipe_tag_recipe_id_fkey foreign KEY (recipe_id) references recipes (recipe_id) on update CASCADE on delete CASCADE,
  constraint recipe_tag_tag_id_fkey foreign KEY (tag_id) references tags (tag_id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

